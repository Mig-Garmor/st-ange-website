export function reviewsForService(slug, limit = 3) {
  const matching = reviews.filter((review) => review.services.includes(slug));
  // Rotating the general reviews per service keeps pages without matches from repeating each other.
  const offset = Math.max(services.findIndex((service) => service.slug === slug), 0) % generalReviews.length;
  const general = [...generalReviews.slice(offset), ...generalReviews.slice(0, offset)];
  return {
    hasMatches: matching.length > 0,
    cards: [
      ...matching.map((review) => toCard(review, serviceName(slug))),
      ...general.map((review) => toCard(review, "")),
    ].slice(0, limit),
  };
}
