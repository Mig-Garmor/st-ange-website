export const reviewById = (id) => {
  const review = reviews.find((r) => r.id === id);
  if (!review) throw new Error(`Unknown review id: ${id}`);
  return review;
};

// A link whose text says whose review it is and what it covers, so readers and AI tools know what it points to.
export const reviewSource = (id, about) => {
  const review = reviewById(id);
  return { href: review.url, label: `${review.author}'s Google review: ${about}` };
};

